export function getInitialRelations(playerCountryId: CountryId): CountryRelation[] {
  const relationScores: Partial<Record<CountryId, number>> = {
    germany: 70,
    uk: 65,
    italy: 60,
    usa: 55,
    japan: 50,
    south_korea: 40,
    brazil: 30,
    saudi_arabia: 20,
    india: 15,
    turkey: 5,
    china: -15,
    russia: -30,
    iran: -50,
    israel: 10,
  };

  return (Object.keys(COUNTRIES) as CountryId[])
    .filter((id) => id !== playerCountryId)
    .map((id) => {
      const score = relationScores[id] ?? 0;
      return {
        countryId: id,
        status: scoreToStatus(score),
        score,
        threatLevel: Math.max(0, Math.round(-score * 0.5 + 25)),
        operationCooldowns: {},
      };
    });
}

function scoreToStatus(score: number): CountryRelation["status"] {
  if (score >= 60) return "allied";
  if (score >= 25) return "friendly";
  if (score >= -25) return "neutral";
  if (score >= -60) return "rival";
  return "hostile";
}

